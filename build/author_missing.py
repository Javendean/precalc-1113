def item(iid, kc, diff, secs, stem, hint, worked, correct, wrong):
    """wrong is a list of (text, misconception_id_or_None)."""
    opts = [{"key": "a", "text": correct, "correct": True}]
    for i, (txt, mis) in enumerate(wrong):
        opts.append({"key": "bcd"[i], "text": txt, "correct": False, "mis": mis})
    return {"id": iid, "kc": kc, "difficulty": diff, "est_seconds": secs,
            "stem": stem, "hint": hint, "worked": worked, "options": opts,
            "source": "hand"}


